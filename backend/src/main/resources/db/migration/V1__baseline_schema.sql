CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    slug        VARCHAR(100) NOT NULL UNIQUE,
    image_url   VARCHAR(255),
    sort_order  INTEGER,
    parent_id   BIGINT REFERENCES categories (id)
);

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    subtitle        VARCHAR(255),
    description     TEXT,
    price           NUMERIC(12, 0) NOT NULL,
    discount_price  NUMERIC(38, 2),
    image_url       TEXT,
    brand           VARCHAR(255),
    category_id     BIGINT REFERENCES categories (id),
    stock           INTEGER NOT NULL,
    active          BOOLEAN NOT NULL,
    created_at      TIMESTAMP(6)
);

CREATE TABLE product_specs (
    product_id   BIGINT NOT NULL REFERENCES products (id),
    sort_order   INTEGER NOT NULL,
    spec_key     VARCHAR(100) NOT NULL,
    spec_value   VARCHAR(500) NOT NULL,
    PRIMARY KEY (product_id, sort_order)
);

CREATE TABLE product_images (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    data          BYTEA NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    sort_order    INTEGER NOT NULL
);
CREATE INDEX idx_product_images_product ON product_images (product_id);

CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(100) NOT NULL UNIQUE,
    password       VARCHAR(255) NOT NULL,
    full_name      VARCHAR(100) NOT NULL,
    phone          VARCHAR(20),
    enabled        BOOLEAN NOT NULL,
    created_at     TIMESTAMP(6),
    updated_at     TIMESTAMP(6),
    last_login_at  TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE user_roles (
    user_id  BIGINT NOT NULL REFERENCES users (id),
    role     VARCHAR(255) NOT NULL,
    PRIMARY KEY (user_id, role)
);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash  VARCHAR(64) NOT NULL UNIQUE,
    user_id     BIGINT NOT NULL REFERENCES users (id),
    expires_at  TIMESTAMP(6) NOT NULL,
    created_at  TIMESTAMP(6) NOT NULL
);

CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES users (id),
    total_amount      NUMERIC(14, 0) NOT NULL,
    status            VARCHAR(255) NOT NULL,
    shipping_address  VARCHAR(255) NOT NULL,
    phone             VARCHAR(20) NOT NULL,
    created_at        TIMESTAMP(6),
    updated_at        TIMESTAMP(6)
);

CREATE TABLE order_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES orders (id),
    product_id    BIGINT REFERENCES products (id),
    product_name  VARCHAR(255) NOT NULL,
    unit_price    NUMERIC(12, 0) NOT NULL,
    quantity      INTEGER NOT NULL,
    subtotal      NUMERIC(14, 0) NOT NULL
);

CREATE TABLE banners (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position      VARCHAR(20) NOT NULL,
    title         VARCHAR(200),
    link_url      VARCHAR(500),
    data          BYTEA NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    sort_order    INTEGER NOT NULL,
    active        BOOLEAN NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE brands (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    link_url      VARCHAR(500),
    data          BYTEA NOT NULL,
    content_type  VARCHAR(100) NOT NULL,
    sort_order    INTEGER NOT NULL,
    active        BOOLEAN NOT NULL,
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE home_products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type        VARCHAR(20) NOT NULL,
    product_id  BIGINT NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    sort_order  INTEGER NOT NULL,
    ends_at     TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_home_products_type ON home_products (type);

CREATE TABLE site_settings (
    setting_key    VARCHAR(60) PRIMARY KEY,
    setting_value  TEXT
);

CREATE TABLE visitor_day (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_date  DATE NOT NULL,
    visitor_id  VARCHAR(36) NOT NULL,
    user_id     BIGINT,
    first_seen  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_visitor_day UNIQUE (visit_date, visitor_id)
);
CREATE INDEX idx_visitor_day_date ON visitor_day (visit_date);

CREATE TABLE daily_visit_stats (
    stat_date       DATE PRIMARY KEY,
    total_visitors  BIGINT NOT NULL,
    user_visitors   BIGINT NOT NULL,
    guest_visitors  BIGINT NOT NULL,
    saved_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
